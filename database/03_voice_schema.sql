-- =============================================================================
-- TABLE: sarvam_api_keys
-- Tracks which SARVAM_API_KEY_N environment variables are exhausted.
-- Keys are stored in .env (SARVAM_API_KEY_1, SARVAM_API_KEY_2, etc.).
-- When a key returns a 402 (quota exceeded), it's marked exhausted here
-- and the next key is tried automatically.
--
-- NOTE: The actual key values are NOT stored in this table — only a hash/prefix
-- for lookup and display. Keys live in environment variables only.
-- =============================================================================
CREATE TABLE IF NOT EXISTS sarvam_api_keys (
  id           INT AUTO_INCREMENT PRIMARY KEY,
  key_hash     VARCHAR(32)  NOT NULL UNIQUE  COMMENT 'MD5 fingerprint of the key for lookup (not the full key)',
  key_prefix   VARCHAR(30)  NOT NULL         COMMENT 'First 20 chars for admin display (e.g. sarvam_sk_abc...)',
  is_exhausted TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '1 = 402 received, skip this key',
  exhausted_at TIMESTAMP    NULL             COMMENT 'When the key was marked exhausted',
  created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =============================================================================
-- TABLE: pending_voice_messages
-- Voice messages generated by cron jobs (proactive messaging), stored here
-- until the user opens the chat and the client polls /api/voice/pending.
--
-- Flow:
--   1. Cron fires → src/app/api/cron/proactive/route.ts
--   2. Message text inserted into this table with is_delivered = 0
--   3. User opens chat → client polls /api/voice/pending
--   4. Audio generated lazily via Sarvam/ElevenLabs TTS
--   5. Row marked is_delivered = 1
--   6. Rows expire after 24h (expires_at) and are cleaned up after 48h
--
-- NOTE: UUID() primary key requires MySQL 8.0+. On MySQL 5.7 the DEFAULT
-- expression won't work — the app generates UUIDs in application code
-- (src/lib/mysql-client.ts) before inserting.
-- =============================================================================
CREATE TABLE IF NOT EXISTS pending_voice_messages (
  id            VARCHAR(36)  NOT NULL PRIMARY KEY    COMMENT 'UUID generated by application code',
  session_id    VARCHAR(255) NOT NULL                COMMENT 'Browser session this message is for',
  text_content  TEXT         NOT NULL                COMMENT 'Text to convert to audio (TTS is lazy)',
  language_code VARCHAR(20)  NOT NULL DEFAULT 'hi-IN' COMMENT 'BCP-47 language tag for TTS',
  message_type  VARCHAR(50)  NOT NULL DEFAULT 'proactive' COMMENT 'proactive | reengagement | morning | evening',
  is_delivered  TINYINT(1)   NOT NULL DEFAULT 0,
  created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at    TIMESTAMP    NOT NULL               COMMENT 'Set to NOW() + 24 HOUR by application code',

  INDEX idx_session_undelivered (session_id, is_delivered, expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

